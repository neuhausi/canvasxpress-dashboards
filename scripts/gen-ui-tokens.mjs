/**
 * Generate src/uiTokens.js from the CanvasXpress engine's design tokens
 * (canvas-ai/tools/ui-consistency/tokens.json -- the ONE token source for the engine and this
 * package).
 *
 * The dashboards style themselves with the engine's --cx-ui-* roles and primitives, which
 * canvasXpress.css defines (every dashboards page loads it). This writes the same tokens as a
 * zero-specificity `:where(:root)` FALLBACK block, so a page without canvasXpress.css still gets
 * them -- and the engine's own `:root` rules always win when it is loaded. Being generated, the
 * fallbacks can never drift from the engine the way the hand-written ones did.
 *
 * It also writes the same block as plain CSS to examples/ui-tokens.css, for the static pages that
 * load neither canvasXpress.css nor the bundle (the examples gallery).
 *
 *   node scripts/gen-ui-tokens.mjs            # write src/uiTokens.js + examples/ui-tokens.css
 *   node scripts/gen-ui-tokens.mjs --check    # exit 1 if either is stale
 *
 * Env: CX_TOKENS (path to tokens.json; default ../canvas-ai/tools/ui-consistency/tokens.json).
 * The output is committed, so building the package does not need the engine checkout.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

var here = dirname(fileURLToPath(import.meta.url));
var root = join(here, '..');
var tokensPath = resolve(process.env.CX_TOKENS || join(root, '..', 'canvas-ai', 'tools', 'ui-consistency', 'tokens.json'));
// The engine's generated light/dark theme blocks (data-cx-ui-theme), next to tokens.json's engine
var themePath = resolve(process.env.CX_THEME_CSS || join(dirname(tokensPath), '..', '..', 'build', 'css', 'widgets', '01b-theme-dark.css'));
var outPath = join(root, 'src', 'uiTokens.js');
var cssPath = join(root, 'examples', 'ui-tokens.css');
var check = process.argv.indexOf('--check') >= 0;

if (!existsSync(tokensPath)) {
  console.error('gen-ui-tokens: tokens.json not found at ' + tokensPath + ' (set CX_TOKENS)');
  process.exit(check ? 1 : 2);
}
var T = JSON.parse(readFileSync(tokensPath, 'utf8'));

var PREFIX = { color: '--cx-color-', radius: '--cx-radius-', space: '--cx-space-', font: '--cx-font-',
  fontSize: '--cx-font-size-', fontWeight: '--cx-font-weight-', lineHeight: '--cx-line-height-',
  shadow: '--cx-shadow-', duration: '--cx-duration-', z: '--cx-z-' };

function ref(v) {
  var m = String(v).match(/^\{([\w-]+)\.([\w-]+)\}$/);
  return m ? 'var(' + PREFIX[m[1]] + m[2] + ')' : v;
}

var decls = [];
Object.keys(PREFIX).forEach(function (group) {
  Object.keys(T.primitive[group]).forEach(function (k) {
    decls.push(PREFIX[group] + k + ': ' + T.primitive[group][k] + ';');
  });
});
Object.keys(T.semantic.light).forEach(function (k) {
  decls.push('--cx-ui-' + k + ': ' + ref(T.semantic.light[k]) + ';');
});

var css = ':where(:root) { ' + decls.join(' ') + ' }';
// One dark mode: the engine's theme blocks, verbatim minus comments, so
// data-cx-ui-theme="light|dark|auto" works on a page without canvasXpress.css too
if (!existsSync(themePath)) {
  console.error('gen-ui-tokens: 01b-theme-dark.css not found at ' + themePath + ' (set CX_THEME_CSS)');
  process.exit(check ? 1 : 2);
}
var themeCss = readFileSync(themePath, 'utf8').replace(/@charset[^;]*;/, '').replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\n\s*\n+/g, '\n').trim();
var out = '/**\n' +
  ' * GENERATED by scripts/gen-ui-tokens.mjs from the CanvasXpress engine\'s\n' +
  ' * tools/ui-consistency/tokens.json (version ' + T.version + '). Do not edit by hand.\n' +
  ' *\n' +
  ' * The engine design tokens as a zero-specificity fallback: canvasXpress.css defines the same\n' +
  ' * properties on :root and always wins; these only apply when it is not loaded.\n' +
  ' *\n' +
  ' * @module uiTokens\n' +
  ' */\n\n' +
  '/** @type {string} */\n' +
  'export var uiTokenCss = ' + JSON.stringify(css + '\n' + themeCss) + ';\n';

var cssOut = '/* GENERATED by scripts/gen-ui-tokens.mjs from the CanvasXpress engine\'s tokens.json (version ' +
  T.version + '). Do not edit by hand.\n * The engine design tokens as a zero-specificity fallback (canvasXpress.css wins when loaded). */\n' +
  css.replace(/; /g, ';\n  ').replace('{ ', '{\n  ').replace(' }', '\n}') + '\n' + themeCss + '\n';

if (check) {
  var stale = [];
  if ((existsSync(outPath) ? readFileSync(outPath, 'utf8') : '') !== out) {
    stale.push('src/uiTokens.js');
  }
  if ((existsSync(cssPath) ? readFileSync(cssPath, 'utf8') : '') !== cssOut) {
    stale.push('examples/ui-tokens.css');
  }
  if (stale.length) {
    console.error(stale.join(' and ') + ' stale: run node scripts/gen-ui-tokens.mjs');
    process.exit(1);
  }
  console.log('src/uiTokens.js + examples/ui-tokens.css up to date (' + decls.length + ' tokens).');
} else {
  writeFileSync(outPath, out);
  writeFileSync(cssPath, cssOut);
  console.log('wrote src/uiTokens.js + examples/ui-tokens.css (' + decls.length + ' tokens from ' + tokensPath + ')');
}
